    /// The character for one byte, with the variation selector added where the scalar has
    /// no emoji presentation of its own.
    public static func displayString(for byte: UInt8) -> String {
        let scalar = scalars[Int(byte)]
        var text = String(scalar)
        if !scalar.properties.isEmojiPresentation {
            text.unicodeScalars.append("\u{FE0F}")
        }
        return text
    }
